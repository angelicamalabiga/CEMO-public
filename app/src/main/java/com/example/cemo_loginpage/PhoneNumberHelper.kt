package com.example.cemo_loginpage

object PhoneNumberHelper {

    private val VALID_PREFIXES = setOf(
        // Globe / TM
        "0817", "0905", "0906", "0915", "0916", "0917", "0926", "0927",
        "0935", "0936", "0937", "0945", "0955", "0956", "0965", "0966",
        "0967", "0975", "0976", "0977", "0995", "0996", "0997",
        // Smart / TNT
        "0813", "0907", "0908", "0909", "0910", "0911", "0912", "0913",
        "0914", "0918", "0919", "0920", "0921", "0928", "0929", "0930",
        "0938", "0939", "0940", "0946", "0947", "0948", "0949", "0950",
        "0951", "0961", "0963", "0968", "0969", "0970", "0981", "0989",
        "0992", "0998", "0999",
        // DITO
        "0895", "0896", "0897", "0898", "0991", "0993", "0994",
        // Sun
        "0922", "0923", "0924", "0925", "0931", "0932", "0933", "0934",
        "0941", "0942", "0943", "0944"
    )

    fun isValidPhMobile(number: String): Boolean {
        if (number.length != 11 || !number.all { it.isDigit() }) return false
        return number.substring(0, 4) in VALID_PREFIXES
    }
}